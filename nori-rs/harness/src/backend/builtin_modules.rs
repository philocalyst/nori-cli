//! The Pkl modules Nori ships ([docs/pkl-runtime.md]): skills such as `impact` and `council`.
//!
//! They are embedded in the binary and written to `$NORI_HOME/builtin/<kind>/` each time modules
//! load, so the catalog reads them as its lowest root (`Scope::Builtin`) and everything that
//! works from a module's file (the evaluator's relative imports, `skill.path`, the watcher) keeps
//! working. A module of the same name in `$NORI_HOME/<kind>/` or a trusted project's
//! `.nori/<kind>/` shadows the built-in one. The directory is generated: files in it are
//! overwritten, and files Nori no longer ships are removed, so copy a module out to change it.
//!
//! [docs/pkl-runtime.md]: ../../../docs/pkl-runtime.md

use std::path::Path;
use std::path::PathBuf;

use nori_pkl::catalog::Problem;

/// Each shipped module, as its path under `builtin/` and its source.
const MODULES: &[(&str, &str)] = &[
    (
        "skills/council.pkl",
        include_str!("../../builtin/skills/council.pkl"),
    ),
    (
        "skills/impact.pkl",
        include_str!("../../builtin/skills/impact.pkl"),
    ),
];

const README: &str = "Generated by Nori on every start; edits here are overwritten.\n\
Copy a module to ../skills/ (or a project's .nori/skills/) to change it: a module there\n\
replaces the built-in one of the same name.\n";

/// Write the shipped modules under `nori_home/builtin/`, only where the content differs, each by
/// an atomic rename, and remove the modules that are no longer shipped. Blocking: it reads and
/// writes files, so call it off the event loop. A failure is a [`Problem`] to show once; the
/// modules already written still load.
pub(super) fn materialize(nori_home: &Path) -> Result<(), Problem> {
    let root = nori_home.join("builtin");
    write_all(&root).map_err(|error| Problem {
        path: root.clone(),
        message: format!(
            "could not write Nori's built-in skills to {}: {error}; `council` and `impact` are unavailable",
            root.display()
        ),
    })
}

fn write_all(root: &Path) -> std::io::Result<()> {
    let mut wanted: Vec<PathBuf> = Vec::new();
    for (relative, source) in MODULES.iter().copied().chain([("README.txt", README)]) {
        let path = root.join(relative);
        wanted.push(path.clone());
        if std::fs::read_to_string(&path).is_ok_and(|current| current == source) {
            continue;
        }
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        let staging = path.with_extension(format!("tmp-{}", std::process::id()));
        std::fs::write(&staging, source)?;
        std::fs::rename(&staging, &path)?;
    }
    for kind in MODULES
        .iter()
        .filter_map(|(relative, _)| Path::new(relative).parent())
    {
        let Ok(entries) = std::fs::read_dir(root.join(kind)) else {
            continue;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.extension().is_some_and(|extension| extension == "pkl")
                && !wanted.contains(&path)
            {
                std::fs::remove_file(&path)?;
            }
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use pretty_assertions::assert_eq;

    use super::*;

    fn listing(root: &Path) -> Vec<String> {
        let mut found: Vec<String> = std::fs::read_dir(root.join("skills"))
            .expect("skills dir")
            .flatten()
            .map(|entry| entry.file_name().to_string_lossy().into_owned())
            .collect();
        found.sort();
        found
    }

    #[test]
    fn modules_are_written_refreshed_and_pruned() {
        let home = tempfile::tempdir().expect("tempdir");
        materialize(home.path()).expect("written");
        let builtin = home.path().join("builtin");
        assert_eq!(listing(&builtin), vec!["council.pkl", "impact.pkl"]);
        for (relative, source) in MODULES {
            assert_eq!(
                std::fs::read_to_string(builtin.join(relative)).expect("module"),
                *source
            );
        }

        // A hand edit is undone, and a module that is no longer shipped is removed.
        std::fs::write(builtin.join("skills/impact.pkl"), "edited").expect("edit");
        std::fs::write(builtin.join("skills/old.pkl"), "stale").expect("stale");
        materialize(home.path()).expect("written again");
        assert_eq!(listing(&builtin), vec!["council.pkl", "impact.pkl"]);
        assert_eq!(
            std::fs::read_to_string(builtin.join("skills/impact.pkl")).expect("module"),
            MODULES[1].1
        );
    }

    #[test]
    fn an_unwritable_home_is_one_problem() {
        let home = tempfile::tempdir().expect("tempdir");
        let file = home.path().join("not-a-directory");
        std::fs::write(&file, "x").expect("file");
        let problem = materialize(&file).expect_err("cannot write under a file");
        assert_eq!(problem.path, file.join("builtin"));
    }
}
